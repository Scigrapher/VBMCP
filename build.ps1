param(
    [switch]$Clean,
    [switch]$Tests
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$BuildDir = Join-Path $Root "build"
$ObjDir = Join-Path $BuildDir "obj"
$BinDir = Join-Path $Root "bin"

function Resolve-VcVars {
    $candidates = @(
        "${env:ProgramFiles}\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars32.bat",
        "${env:ProgramFiles}\Microsoft Visual Studio\2022\Professional\VC\Auxiliary\Build\vcvars32.bat",
        "${env:ProgramFiles}\Microsoft Visual Studio\2022\Enterprise\VC\Auxiliary\Build\vcvars32.bat",
        "${env:ProgramFiles(x86)}\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars32.bat"
    )
    foreach ($candidate in $candidates) {
        if (Test-Path -LiteralPath $candidate) { return $candidate }
    }
    $vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
    if (Test-Path -LiteralPath $vswhere) {
        $install = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
        if ($install) {
            $candidate = Join-Path $install "VC\Auxiliary\Build\vcvars32.bat"
            if (Test-Path -LiteralPath $candidate) { return $candidate }
        }
    }
    throw "Visual Studio x86 C++ tools were not found."
}

function Invoke-Native {
    param(
        [string]$Command,
        [string]$LogPath,
        [string]$Description
    )
    $batch = Join-Path $BuildDir ("run-" + [guid]::NewGuid().ToString("N") + ".cmd")
    @(
        "@echo off",
        "call `"$VcVars`" >nul",
        $Command,
        "exit /b %ERRORLEVEL%"
    ) | Set-Content -LiteralPath $batch -Encoding ASCII
    $output = @(& cmd.exe /d /s /c "`"$batch`"" 2>&1)
    $code = $LASTEXITCODE
    [System.IO.File]::WriteAllText($LogPath, (($output | ForEach-Object { $_.ToString() }) -join "`r`n") + "`r`n")
    Remove-Item -LiteralPath $batch -Force
    if ($code -ne 0) {
        Write-Host "--- $Description failed (exit $code) ---" -ForegroundColor Red
        Get-Content -LiteralPath $LogPath | ForEach-Object { Write-Host $_ }
        throw "$Description failed"
    }
    $warnings = Get-Content -LiteralPath $LogPath | Select-String -Pattern "warning C|warning LNK"
    if ($warnings) {
        Write-Host "$Description completed with warnings:" -ForegroundColor Yellow
        $warnings | Select-Object -First 20 | ForEach-Object { Write-Host $_.Line }
    }
}

function Assert-SafeChildPath {
    param([string]$Path, [string]$Parent)
    $resolvedParent = [System.IO.Path]::GetFullPath($Parent).TrimEnd('\') + '\'
    $resolvedPath = [System.IO.Path]::GetFullPath($Path)
    if (-not $resolvedPath.StartsWith($resolvedParent, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to modify path outside build root: $resolvedPath"
    }
}

if ($Clean -and (Test-Path -LiteralPath $BuildDir)) {
    $resolved = [System.IO.Path]::GetFullPath($BuildDir)
    $resolvedRoot = [System.IO.Path]::GetFullPath($Root).TrimEnd('\') + '\'
    if (-not $resolved.StartsWith($resolvedRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to clean outside the add-in directory."
    }
    Remove-Item -LiteralPath $BuildDir -Recurse -Force
}

New-Item -ItemType Directory -Force -Path $BuildDir, $ObjDir, $BinDir | Out-Null
$VcVars = Resolve-VcVars

$Definition = @"
WIN32_LEAN_AND_MEAN
NOMINMAX
UNICODE
_UNICODE
WIN32
_WIN32_WINNT=0x0501
WINVER=0x0501
_CRT_SECURE_NO_WARNINGS
_CRT_NONSTDC_NO_WARNINGS
"@

$CompileFlags = "/nologo /c /EHsc /std:c++14 /W4 /O2 /MT /DUNICODE /D_UNICODE /DWIN32 /D_WIN32_WINNT=0x0501 /DWINVER=0x0501 /D_CRT_SECURE_NO_WARNINGS /D_CRT_NONSTDC_NO_WARNINGS /I `"$Root\src`" /Fo`"$ObjDir\\`""

$ProductionSources = @(
    "src\common.cpp",
    "src\json.cpp",
    "src\config.cpp",
    "src\log.cpp",
    "src\project_files.cpp",
    "src\tools.cpp",
    "src\tls.cpp",
    "src\http_server.cpp",
    "src\mcp_server.cpp",
    "src\com_ide.cpp",
    "src\addin.cpp",
    "src\dllmain.cpp",
    "src\compat_xp.cpp"
) | ForEach-Object { Join-Path $Root $_ }

$BannedKernelFunctions = @(
    "InitializeCriticalSectionEx", "FlsAlloc", "FlsFree", "FlsGetValue", "FlsSetValue",
    "AcquireSRWLockExclusive", "ReleaseSRWLockExclusive", "SleepConditionVariableSRW",
    "WakeAllConditionVariable"
)

Write-Host "Generating XP kernel32 import metadata..." -ForegroundColor Cyan
$kernelSymbols = Get-Content -LiteralPath (Join-Path $Root "src\kernel32_symbols.txt")
$defLines = @("LIBRARY KERNEL32.dll", "EXPORTS")
$aliasLines = @(
    "// Generated by build.ps1.",
    "extern `"C`" int g_xp_kernel32_aliases = 0;"
)
foreach ($entry in $kernelSymbols) {
    if ($entry -notmatch "^([A-Za-z][A-Za-z0-9_]*)@([0-9]+)$") { continue }
    $function = $Matches[1]
    $stackBytes = $Matches[2]
    if ($BannedKernelFunctions -contains $function) { continue }
    $defLines += "$function=KERNEL32.$function"
    $aliasLines += "#pragma comment(linker, `"/alternatename:_$function@$stackBytes=_$function`")"
    $aliasLines += "#pragma comment(linker, `"/alternatename:__imp__$function@$stackBytes=__imp__$function`")"
}
$GeneratedDef = Join-Path $BuildDir "xp_kernel32.def"
$GeneratedAliases = Join-Path $BuildDir "xp_kernel32_aliases.cpp"
$defLines | Set-Content -LiteralPath $GeneratedDef -Encoding ASCII
$aliasLines | Set-Content -LiteralPath $GeneratedAliases -Encoding ASCII
$ProductionSources += $GeneratedAliases

Write-Host "Compiling MCPAddin.dll objects..." -ForegroundColor Cyan
$compileCommand = "cl $CompileFlags " + (($ProductionSources | ForEach-Object { "`"$_`"" }) -join " ")
Invoke-Native -Command $compileCommand -LogPath (Join-Path $BuildDir "compile-dll.log") -Description "DLL compilation"

$KernelLib = Join-Path $BuildDir "xp_kernel32.lib"
Write-Host "Creating XP-compatible kernel32 import library..." -ForegroundColor Cyan
Invoke-Native -Command "lib /nologo /def:`"$GeneratedDef`" /machine:x86 /out:`"$KernelLib`"" `
    -LogPath (Join-Path $BuildDir "lib-kernel32.log") -Description "kernel32 import library"

$ObjFiles = Get-ChildItem -LiteralPath $ObjDir -Filter "*.obj" | Sort-Object Name | ForEach-Object {
    "`"$($_.FullName)`""
}
$DllPath = Join-Path $BinDir "MCPAddin.dll"
$LinkCommand = "link /nologo /NODEFAULTLIB:kernel32.lib /IGNORE:4217 /INCREMENTAL:NO /OPT:REF /OPT:ICF /NOEXP /NOIMPLIB " +
    "/DLL /MACHINE:X86 /SUBSYSTEM:WINDOWS,5.01 /OSVERSION:5.01 " +
    "/OUT:`"$DllPath`" /DEF:`"$Root\src\mcpaddin.def`" " +
    (($ObjFiles) -join " ") +
    " `"$KernelLib`" ole32.lib oleaut32.lib advapi32.lib shell32.lib user32.lib ws2_32.lib crypt32.lib secur32.lib"
Write-Host "Linking MCPAddin.dll..." -ForegroundColor Cyan
Invoke-Native -Command $LinkCommand -LogPath (Join-Path $BuildDir "link-dll.log") -Description "DLL link"

if ($Tests) {
    Write-Host "Compiling simulated-IDE test runner..." -ForegroundColor Cyan
    $testObjDir = Join-Path $BuildDir "test-obj"
    New-Item -ItemType Directory -Force -Path $testObjDir | Out-Null
    $testSources = @(
        "src\common.cpp",
        "src\json.cpp",
        "src\config.cpp",
        "src\log.cpp",
        "src\project_files.cpp",
        "src\tools.cpp",
        "src\tls.cpp",
        "src\http_server.cpp",
        "src\mcp_server.cpp",
        "tests\mock_ide.cpp",
        "tests\selftest.cpp"
    ) | ForEach-Object { Join-Path $Root $_ }
    $testCompile = "cl /nologo /c /EHsc /std:c++14 /W4 /O2 /MT /DUNICODE /D_UNICODE /DWIN32 /D_WIN32_WINNT=0x0501 /DWINVER=0x0501 /D_CRT_SECURE_NO_WARNINGS /D_CRT_NONSTDC_NO_WARNINGS " +
        "/I `"$Root\src`" /I `"$Root\tests`" /Fo`"$testObjDir\\`" " +
        (($testSources | ForEach-Object { "`"$_`"" }) -join " ")
    Invoke-Native -Command $testCompile -LogPath (Join-Path $BuildDir "compile-tests.log") -Description "test compilation"
    $testObjs = Get-ChildItem -LiteralPath $testObjDir -Filter "*.obj" | Sort-Object Name | ForEach-Object {
        "`"$($_.FullName)`""
    }
    $testExe = Join-Path $BinDir "mcpaddin_selftest.exe"
    $testLink = "link /nologo /INCREMENTAL:NO /OPT:REF /OPT:ICF /MACHINE:X86 /SUBSYSTEM:CONSOLE " +
        "/OUT:`"$testExe`" " + (($testObjs) -join " ") +
        " ole32.lib oleaut32.lib advapi32.lib shell32.lib user32.lib ws2_32.lib crypt32.lib secur32.lib"
    Invoke-Native -Command $testLink -LogPath (Join-Path $BuildDir "link-tests.log") -Description "test link"
}

$dumpbin = $null
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
if (Test-Path -LiteralPath $vswhere) {
    $install = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if ($install) {
        $candidate = Get-ChildItem -Path (Join-Path $install "VC\Tools\MSVC") -Filter dumpbin.exe -Recurse |
            Where-Object { $_.FullName -match "Hostx64\\x86" } | Select-Object -First 1
        if ($candidate) { $dumpbin = $candidate.FullName }
    }
}
if ($dumpbin) {
    $imports = & $dumpbin /nologo /imports $DllPath
    $forbidden = @(
        "InitializeCriticalSectionEx", "FlsAlloc", "FlsFree", "FlsGetValue", "FlsSetValue",
        "AcquireSRWLockExclusive", "ReleaseSRWLockExclusive", "SleepConditionVariableSRW",
        "WakeAllConditionVariable", "InitializeConditionVariable", "GetSystemTimePreciseAsFileTime",
        "CreateFile2", "GetTempPath2W", "SetThreadDescription"
    )
    $violations = $imports | Select-String -Pattern ($forbidden -join "|")
    if ($violations) {
        $violations | ForEach-Object { Write-Host $_.Line -ForegroundColor Red }
        throw "The built DLL contains post-XP imports."
    }
    $dllName = ""
    $kernelImports = @()
    foreach ($line in $imports) {
        if ($line -match "^\s+([A-Za-z0-9_\.]+\.dll)\s*$") {
            $dllName = $Matches[1]
        } elseif ($dllName -ieq "KERNEL32.dll" -and $line -match "^\s+[0-9A-F]+\s+([A-Za-z_][A-Za-z0-9_]*)\s*$") {
            $kernelImports += $Matches[1]
        }
    }
    $allowlist = Get-Content -LiteralPath (Join-Path $Root "src\xp_kernel32_allowed.txt")
    $unknown = $kernelImports | Sort-Object -Unique | Where-Object { $allowlist -notcontains $_ }
    if ($unknown) {
        $unknown | ForEach-Object { Write-Host "Unexpected KERNEL32 import: $_" -ForegroundColor Red }
        throw "The built DLL imports a kernel API that is not on the reviewed XP allow-list."
    }
    Write-Host "XP import check passed (reviewed KERNEL32 allow-list)." -ForegroundColor Green
}

Write-Host "Built: $DllPath" -ForegroundColor Green
if ($Tests) { Write-Host "Built: $(Join-Path $BinDir 'mcpaddin_selftest.exe')" -ForegroundColor Green }
